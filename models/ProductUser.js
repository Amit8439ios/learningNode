const mongoose = require('mongoose')

const productUserSchema = new mongoose.Schema(
    {
        firstName: {
            type: String,
            required: true,
            trim: true
        },
        lastName: {
            type: String,
            required: true,
            trim: true
        },
        email: {
            type: String,
            required: true,
            unique: true,
            trim: true,
            lowercase: true
        },
        password: {
            type: String,
            required: true,
            select: false
        }
    }, {
    timestamps: true
}
)

module.exports = mongoose.model("ProductUser", productUserSchema)